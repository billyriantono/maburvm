#!/usr/bin/env bash
# Install the panel on a new host (docs/DEPLOYMENT.md, Installing the panel).
#
# Run as root from a release directory (a checkout, or the source archive of a
# release tag) on a host that does not run MaburVM yet:
#
#   scripts/install-panel.sh --url https://panel.example.com
#   scripts/install-panel.sh --url https://panel.example.com \
#       --version v1.2.0 --image-prefix ghcr.io/OWNER/maburvm
#
#   --url URL           the address people open, served by your TLS proxy (required)
#   --version TAG       run that published release; with --image-prefix.
#                       Without them, panel and web are built here from this directory.
#   --image-prefix P    where the release images are published
#   --web-port N        loopback port your proxy forwards to (default 3000)
#   --force             install even though this host runs virtual machines
#
# It checks the host, writes .env.production and the secret files with random
# values, starts the stack and prints the link that creates the first
# administrator. It never overwrites an install: run again, it changes nothing.
set -euo pipefail

usage() {
  sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'
  exit 2
}
log() { printf '==> %s\n' "$*"; }
warn() { printf 'WARNING: %s\n' "$*" >&2; }
die() {
  printf 'install-panel: %s\n' "$*" >&2
  exit 1
}

URL="" VERSION="" PREFIX="" WEB_PORT=3000 FORCE=""
while [ $# -gt 0 ]; do
  case "$1" in
    --url) URL="${2:-}"; shift ;;
    --version) VERSION="${2:-}"; shift ;;
    --image-prefix) PREFIX="${2:-}"; shift ;;
    --web-port) WEB_PORT="${2:-}"; shift ;;
    --force) FORCE=1 ;;
    -h | --help) usage ;;
    *) echo "unknown option $1" >&2; usage ;;
  esac
  shift
done

cd "$(dirname "${BASH_SOURCE[0]}")/.."
ENV_FILE=.env.production
MARKER="# Generated by scripts/install-panel.sh"
[ -f docker-compose.production.yml ] && [ -f .env.production.example ] && [ -d docker/panel-backup ] ||
  die "run this from a MaburVM release directory (docker-compose.production.yml, .env.production.example, docker/)"

compose() { docker compose -f docker-compose.production.yml --env-file "$ENV_FILE" "$@"; }
state() { docker inspect -f "{{$1}}" "$2" 2>/dev/null || true; }
env_set() {
  local tmp
  tmp="$(mktemp "$ENV_FILE.XXXXXX")"
  awk -v k="$1" -v v="$2" 'index($0, k "=") == 1 { if (!done) print k "=" v; done = 1; next } { print } END { if (!done) print k "=" v }' "$ENV_FILE" > "$tmp"
  chmod 600 "$tmp"
  mv "$tmp" "$ENV_FILE"
}
wait_healthy() {
  local c="$1" deadline=$((SECONDS + $2))
  while [ "$SECONDS" -lt "$deadline" ]; do
    [ "$(state .State.Health.Status "$c")" = healthy ] && return 0
    if [ "$(state .State.Status "$c")" != running ] || [ "$(state .RestartCount "$c")" != 0 ]; then
      echo "$c stopped or restarted: it exits when it cannot start" >&2
      return 1
    fi
    sleep 5
  done
  echo "$c did not become healthy within $2 seconds" >&2
  return 1
}
secret() { openssl rand -hex 32 2> /dev/null || od -An -N32 -tx1 /dev/urandom | tr -d ' \n'; }

# --- What is already here -------------------------------------------------------
command -v docker > /dev/null || die "docker is not installed (https://docs.docker.com/engine/install/)"
docker info > /dev/null 2>&1 || die "cannot talk to the docker daemon; run as root, with docker running"
found=()
[ ! -e "$ENV_FILE" ] || found+=("$ENV_FILE")
[ ! -e deploy/secrets/postgres_password ] || found+=(deploy/secrets/postgres_password)
[ ! -e deploy/secrets/s3_restricted_password ] || found+=(deploy/secrets/s3_restricted_password)
for c in maburvm-postgres maburvm-panel maburvm-web; do
  [ -z "$(state .Id "$c")" ] || found+=("container $c")
done
PROJECT="$(basename "$PWD" | tr '[:upper:]' '[:lower:]' | tr -cd 'a-z0-9_-')"
for v in postgres_data panel_data; do
  ! docker volume inspect "${COMPOSE_PROJECT_NAME:-$PROJECT}_$v" > /dev/null 2>&1 || found+=("volume ${COMPOSE_PROJECT_NAME:-$PROJECT}_$v")
done

RESUME=""
if [ "${#found[@]}" -gt 0 ]; then
  if [ "$(state .State.Health.Status maburvm-panel)" = healthy ] && [ -f "$ENV_FILE" ]; then
    log "MaburVM is already installed here. Nothing was changed."
    echo "Upgrade it with scripts/upgrade-panel.sh; see docs/DEPLOYMENT.md."
    exit 0
  fi
  if [ -f "$ENV_FILE" ] && head -n 1 "$ENV_FILE" | grep -qF "$MARKER" &&
    [ -s deploy/secrets/postgres_password ] && [ -s deploy/secrets/s3_restricted_password ]; then
    log "Finishing the install started earlier (its configuration is kept)"
    RESUME=1
  else
    printf '  %s\n' "${found[@]}" >&2
    die "an earlier or partial install is here (above). Refusing to overwrite it: new secrets would lock you out of an existing database. Move it away or finish it by hand."
  fi
fi

# --- Host checks ----------------------------------------------------------------
if [ -z "$RESUME" ]; then
  [ "$(id -u)" = 0 ] || die "run as root: the secret files are written owned by root, mode 0400"
  [[ "$URL" =~ ^https?://[A-Za-z0-9.-]+(:[0-9]+)?/?$ ]] || die "--url must be the panel's address, such as https://panel.example.com (no path)"
  URL="${URL%/}"
  [[ "$URL" == https://* ]] || warn "$URL is plain http: passwords and sessions would cross the network unencrypted. Put a TLS proxy in front and use https."
  [[ "$WEB_PORT" =~ ^[0-9]+$ ]] || die "--web-port takes a port number"
  if [ -n "$VERSION$PREFIX" ]; then
    [ -n "$VERSION" ] && [ -n "$PREFIX" ] || die "--version and --image-prefix go together"
    [[ "$VERSION" =~ ^v[0-9]+\.[0-9]+\.[0-9]+([-+][0-9A-Za-z.-]+)?$ ]] || die "--version takes a release tag such as v1.2.0"
  fi
fi
docker compose version > /dev/null 2>&1 || die "the docker compose plugin (v2) is missing"
# A panel belongs on its own host; this installer never touches a hypervisor's networking.
if command -v virsh > /dev/null 2>&1 && [ -n "$(virsh list --all --name 2> /dev/null | tr -d '[:space:]')" ] && [ -z "$FORCE" ]; then
  die "this host runs virtual machines. Install the panel on a separate machine, or rerun with --force if you are sure"
fi
mem_kb="$(awk '/^MemTotal:/ { print $2 }' /proc/meminfo 2> /dev/null || echo 0)"
[ "${mem_kb:-0}" -ge 1900000 ] || die "the panel needs at least 2 GiB of memory; this host has $((mem_kb / 1024)) MiB"
[ "$mem_kb" -ge 3900000 ] || warn "less than 4 GiB of memory: fine to start, tight once metrics accumulate"
for dir in . "$(docker info -f '{{.DockerRootDir}}' 2> /dev/null || echo /var/lib/docker)"; do
  free_kb="$(df -Pk "$dir" 2> /dev/null | awk 'NR == 2 { print $4 }')"
  [ "${free_kb:-0}" -ge 10485760 ] || die "less than 10 GiB free under $dir"
done
if [ -z "$RESUME" ] && command -v ss > /dev/null; then
  for port in "$WEB_PORT" 8081; do
    [ -z "$(ss -Hltn "sport = :$port" 2> /dev/null)" ] || die "port $port is already in use on this host"
  done
fi

# --- Configuration --------------------------------------------------------------
if [ -z "$RESUME" ]; then
  log "Writing $ENV_FILE and deploy/secrets with random values"
  umask 077
  mkdir -p deploy/secrets
  for f in postgres_password s3_restricted_password; do
    secret | tr -d '\n' > "deploy/secrets/$f"
    chmod 0400 "deploy/secrets/$f"
  done
  { echo "$MARKER on $(date -u +%Y-%m-%dT%H:%M:%SZ)"; cat .env.production.example; } > "$ENV_FILE"
  chmod 600 "$ENV_FILE"
  env_set MINIO_ROOT_USER maburvm-root
  env_set MINIO_ROOT_PASSWORD "$(secret)"
  env_set PANEL_PUBLIC_URL "$URL"
  env_set ALLOWED_ORIGINS "$URL"
  env_set WEB_PORT "$WEB_PORT"
  # Upgrades started without scripts/upgrade-panel.sh then cannot migrate without a fresh dump.
  env_set MIGRATION_REQUIRE_BACKUP_WITHIN 6h
  if [ -n "$VERSION" ]; then
    env_set MABURVM_IMAGE_PREFIX "$PREFIX"
    env_set MABURVM_VERSION "$VERSION"
  fi
fi

# --- Start ----------------------------------------------------------------------
if [ -n "$(sed -n 's/^MABURVM_IMAGE_PREFIX=//p' "$ENV_FILE" | tail -n 1)" ]; then
  log "Pulling the release images"
  compose pull panel web
  compose build panel-backup
else
  GIT_COMMIT="${GIT_COMMIT:-$(git rev-parse HEAD 2> /dev/null || true)}"
  APP_VERSION="${APP_VERSION:-$(git describe --tags --always --dirty 2> /dev/null || true)}"
  BUILD_TIME="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  export GIT_COMMIT APP_VERSION BUILD_TIME
  log "Building the images here (several minutes)"
  compose build panel web panel-backup
fi
log "Starting the stack"
# On a rerun, fresh containers: a panel left restarting by the earlier attempt
# would otherwise fail the health wait at once on its old restart count.
compose up -d --no-build ${RESUME:+--force-recreate} || {
  compose logs --no-color --tail 60 panel || true
  die "the stack did not start; fix the error above and run this script again (it keeps the configuration)"
}
if ! { wait_healthy maburvm-panel 1800 && wait_healthy maburvm-web 300; }; then
  compose logs --no-color --tail 60 panel || true
  die "the panel did not become healthy; fix the error above and run this script again"
fi
compose exec -T panel test -s /data/secrets.json ||
  warn "the panel's key file /data/secrets.json was not found. Without it, a restored database cannot be decrypted"

URL="$(sed -n 's/^PANEL_PUBLIC_URL=//p' "$ENV_FILE" | tail -n 1)"
PORT="$(sed -n 's/^WEB_PORT=//p' "$ENV_FILE" | tail -n 1)"
TOKEN="$(compose exec -T panel cat /data/first-run-token 2> /dev/null | tr -d '[:space:]' || true)"
echo
log "MaburVM is running"
if [ -n "$TOKEN" ]; then
  echo "Create the first administrator (the link works once; keep it private):"
  echo "  $URL/first-run#token=$TOKEN"
else
  echo "This panel already has an administrator. Sign in at $URL/login"
fi
cat << MSG

Next:
  1. Point your TLS reverse proxy at 127.0.0.1:${PORT:-3000} for $URL (docs/DEPLOYMENT.md section 7).
  2. Set BACKUP_DEST and BACKUP_AGE_RECIPIENTS in $ENV_FILE for the nightly off-host
     backup, and keep an offline copy of $ENV_FILE and deploy/secrets (section 9).
  3. Add nodes from the Nodes page. Upgrade later with scripts/upgrade-panel.sh.
MSG
